%% Local functions

function p_adj = holm_adjust(p)

    p = p(:);
    m = numel(p);

    [p_sorted,order] = sort(p);

    adjusted_sorted = zeros(m,1);

    running_max = 0;

    for k = 1:m

        value = ...
            (m-k+1) * p_sorted(k);

        running_max = ...
            max(running_max,value);

        adjusted_sorted(k) = ...
            min(running_max,1);
    end

    p_adj = zeros(m,1);

    p_adj(order) = adjusted_sorted;

    p_adj = p_adj.';
end

function label = sig_from_p(p)

    if p < 0.001

        label = '***';

    elseif p < 0.01

        label = '**';

    elseif p < 0.05

        label = '*';

    else

        label = 'ns';
    end
end

function add_sig_line(ax,x,y,e,labels,base_y)

    yline_sig = ...
        max(base_y,max(y+e)+4);

    tick_h = 1.2;

    plot( ...
        ax, ...
        [x(1) x(end)], ...
        [yline_sig yline_sig], ...
        'k-', ...
        'LineWidth',0.9, ...
        'HandleVisibility','off');

    for j = 1:numel(x)

        plot( ...
            ax, ...
            [x(j) x(j)], ...
            [yline_sig yline_sig-tick_h], ...
            'k-', ...
            'LineWidth',0.9, ...
            'HandleVisibility','off');
    end

    for j = 1:numel(labels)

        text( ...
            ax, ...
            mean(x(j:j+1)), ...
            yline_sig+1.0, ...
            labels{j}, ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','bottom', ...
            'FontSize',20);
    end
end